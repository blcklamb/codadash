import type { SVGProps } from 'react';
type Props = SVGProps<SVGSVGElement> & { size?: number };
// Each filled cell is one pixel on a 12 x 12 grid. No curved strokes or scaling filters.
function icon(rows: string[]) {
  return function PixelIcon({ size = 24, ...props }: Props) {
    return (
      <svg
        width={size}
        height={size}
        viewBox="0 0 12 12"
        fill="currentColor"
        aria-hidden="true"
        shapeRendering="crispEdges"
        {...props}
      >
        {rows.flatMap((row, y) =>
          Array.from(row).map((cell, x) =>
            cell === '#' ? <rect key={`${x}:${y}`} x={x} y={y} width="1" height="1" /> : null,
          ),
        )}
      </svg>
    );
  };
}
